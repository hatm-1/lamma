// توحيد الحروف عشان «أ» و«ا» يعتبرون نفس الحرف
export function normWord(s) {
  return String(s || '')
    .replace(/[ً-ْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/[^ء-ي]/g, '');
}

// تقييم التخمين: 2 = مكانه صح، 1 = موجود بمكان ثاني، 0 = مو موجود
export function scoreGuess(guess, target) {
  const g = [...guess], t = [...target];
  const res = Array(g.length).fill(0);
  const left = {};
  t.forEach((ch, i) => { if (g[i] === ch) res[i] = 2; else left[ch] = (left[ch] || 0) + 1; });
  g.forEach((ch, i) => { if (res[i] !== 2 && left[ch]) { res[i] = 1; left[ch]--; } });
  return res;
}
